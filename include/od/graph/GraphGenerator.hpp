#pragma once

#include "od/config/ManualGenConfig.hpp"
#include "od/graph/Graph.hpp"

namespace od::graph {

/**
 * @brief Строит случайный граф из нескольких уровней и расставляет упрямые вершины.
 *
 * ### Как устроен случайный граф (модель Эрдёша–Реньи)
 *
 * Берём `N` вершин. Для каждой пары вершин подбрасываем «монетку», которая выпадает
 * с вероятностью `p`: выпала — соединяем пару ребром, не выпала — не соединяем.
 * Каждая пара решается отдельно, независимо от остальных.
 *
 * Что из этого получается:
 * - у вершины в среднем `p·(N − 1)` соседей, у всех вершин примерно поровну;
 * - всего рёбер в среднем `p·N·(N − 1)/2`;
 * - если `p` слишком маленькое (меньше примерно `ln N / N`), появляются вершины без соседей
 *   и оторванные куски графа. Вершины без соседей никогда не меняют мнение.
 *
 * Пример: при `N = 50` и `p = 0.3` у вершины в среднем около 15 соседей.
 *
 * ### Уровни
 *
 * Вершины можно разбить на уровни (группы). У уровня `i` своё число вершин `Nᵢ` и своя
 * вероятность связи `pᵢ`:
 * - две вершины одного уровня `i` соединяются с вероятностью `pᵢ`;
 * - вершины разных уровней `i` и `j` — с вероятностью `min(pᵢ, pⱼ)`, то есть с меньшей из двух.
 *
 * Так можно сделать, например, плотную компанию друзей внутри большого и редкого круга
 * знакомых: внутри компании связей много, а с остальными людьми у её участников связей
 * столько же, сколько у остальных между собой. Если уровень один, это обычный граф
 * Эрдёша–Реньи.
 *
 * Номера вершин идут подряд: сначала все вершины первого уровня, потом второго и так далее.
 *
 * ### Веса рёбер
 *
 * Каждое ребро получает случайный вес от 0 до 1 — «силу связи». Вес нужен, если включён
 * учёт весов: тогда сосед с сильной связью влияет на мнение сильнее, чем со слабой.
 *
 * ### Упрямые вершины
 *
 * Ставятся после рёбер, двумя способами:
 * 1. «назначить существующие» — обычная вершина графа становится упрямой. У неё остаются
 *    все её связи, и она влияет на всех своих соседей;
 * 2. «прикрепить новые» — в конец графа добавляется новая вершина (номера `N`, `N + 1`, …)
 *    и соединяется одним ребром с одной вершиной графа. Она влияет только на этого соседа.
 *    К одной вершине графа можно прикрепить несколько упрямых.
 *
 * ### Повторяемость
 *
 * Одни и те же настройки и seed всегда дают один и тот же граф. Генератор берёт случайные
 * числа из своего отдельного источника, поэтому они не совпадают со случайными числами
 * симуляции, даже если seed один и тот же.
 *
 * Строится граф перебором всех пар вершин, поэтому время растёт как квадрат числа вершин:
 * вершин в 2 раза больше — строится в 4 раза дольше.
 *
 * @param config Уровни и группы упрямых вершин. Остальные поля не используются.
 *        Конфигурация должна пройти `od::config::validateConfig`.
 * @param seed Seed генератора случайных чисел.
 * @return Построенный граф.
 * @throws std::invalid_argument Если в группе упрямых число целей не совпадает с количеством
 *         или назначаемых упрямых больше, чем вершин в уровнях.
 * @throws std::out_of_range Если номер цели упрямой вершины вне вершин уровней.
 */
Graph generateGraph(const od::config::ManualGenConfig& config, unsigned int seed);

} // namespace od::graph
