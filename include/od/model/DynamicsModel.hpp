/// @brief Модель: мнения, правила их изменения, динамика рёбер и цикл симуляции.
namespace od::model {

using od::graph::Graph;

/// @brief Мнение и число вершин с этим мнением. Из таких записей состоит история прогона в логе.
struct OpinionCount {
    int opinion; ///< Номер мнения.
    int count;   ///< Число вершин с этим мнением.
};

/**
 * @brief Считает вершины по мнениям.
 * @param opinions Мнения вершин, каждое от 0 до `numOpinions − 1`.
 * @param numOpinions Число мнений.
 * @return Только мнения, которые есть хотя бы у одной вершины, по убыванию числа вершин,
 *         при равенстве — по возрастанию номера мнения.
 */
std::vector<OpinionCount> countOpinions(const std::vector<int>& opinions, int numOpinions);

/// @brief Как вершина выбирает новое мнение.
struct ChoiceSettings {
    ChoiceRule rule = ChoiceRule::Max; ///< Правило выбора.
    std::vector<int> popularity;       ///< Мнения от самого популярного, решают ничьи в правиле `Max`.
};

/**
 * @brief Изменение мнений: один шаг для всех вершин графа.
 *
 * ### Что моделируется
 *
 * У каждой вершины (человека) есть мнение — номер от 0 до `n − 1`. Номера — просто названия,
 * «больше» и «меньше» среди них нет. На каждом шаге вершина смотрит на соседей и может
 * перенять мнение одного из них. Упрямые вершины мнение не меняют никогда, вершины без
 * соседей — тоже: им не у кого перенимать.
 *
 * ### Что происходит с одной вершиной
 *
 * 1. **Считаем доли.** Для каждого мнения соседей — у какой части соседей оно есть:
 *    - без весов: `sₖ = (сколько соседей с мнением k) / (сколько всего соседей)`;
 *    - с весами: то же самое, но каждый сосед считается с весом своего ребра — близкий друг
 *      весит больше, чем дальний знакомый.
 *
 *    Мнения, которых у соседей нет, не рассматриваются.
 * 2. **Считаем вероятности** по функции изменения мнений: `P(k) = gₖ(sₖ) / Σₘ gₘ(sₘ)`.
 *    Если все значения функции нулевые, вершина остаётся при своём мнении.
 * 3. **Выбираем мнение** по правилу «пропорционально» или «максимум» (см. `ChoiceRule`).
 *
 * ### Все вершины меняются одновременно
 *
 * На шаге `t + 1` все вершины смотрят на мнения шага `t`. Если вершина сменила мнение,
 * соседи увидят это только на следующем шаге. Поэтому неважно, в каком порядке обходить
 * вершины: от порядка зависит только то, какое случайное число достанется какой вершине.
 *
 * ### Скорость и повторяемость
 *
 * Время шага пропорционально числу рёбер и не зависит от числа мнений: 10 000 мнений
 * считаются так же быстро, как 2, потому что у каждой вершины рассматриваются только
 * мнения её соседей.
 *
 * Вершины обходятся по возрастанию номера. «Пропорционально» тратит на каждую вершину
 * с соседями одно случайное число, «максимум» — от нуля до двух (на ничью и на монетку).
 * Поэтому при одном и том же seed результат всегда одинаковый, а при правиле
 * «пропорционально» и двух мнениях он совпадает со старыми версиями программы.
 *
 * Объект хранит рабочие буферы, поэтому его создают один раз на прогон.
 */
class OpinionUpdater {
public:
    /**
     * @param rule Правило смены мнений, число мнений — `rule.functions.size()`.
     * @param choice Правило выбора и список популярности.
     * @param useWeights Считать соседей с весами рёбер или все одинаково.
     * @throws std::invalid_argument Если правило не проходит `validateOpinionRule` или в списке
     *         популярности есть мнение вне диапазона или повтор.
     */
    OpinionUpdater(OpinionRule rule, const ChoiceSettings& choice, bool useWeights);

    /// @brief Число мнений в правиле.
    int numOpinions() const noexcept {
        return static_cast<int>(rule_.functions.size());
    }

    /**
     * @brief Один шаг мнений: все вершины одновременно смотрят на мнения предыдущего шага.
     * @param graph Граф.
     * @param current Мнения на предыдущем шаге, каждое от 0 до `numOpinions() − 1`.
     * @param rng Генератор случайных чисел прогона.
     * @return Мнения после шага.
     */
    std::vector<int> step(const Graph& graph, const std::vector<int>& current, std::mt19937& rng);

private:
    const std::vector<OpinionShare>& neighborShares(const Graph& graph, int vertex, const std::vector<int>& opinions);
    int chooseMax(const std::vector<OpinionChance>& chances, int current, std::mt19937& rng);
    int breakTie(std::mt19937& rng);

    OpinionRule rule_;
    ChoiceRule choiceRule_;
    std::vector<int> popularityRank_;
    bool useWeights_;

    std::vector<double> weightByOpinion_;
    std::vector<char> seen_;
    std::vector<int> touched_;
    std::vector<OpinionShare> shares_;
    std::vector<int> tied_;
};

} // namespace od::model
