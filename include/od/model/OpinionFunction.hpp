#pragma once

#include <optional>
#include <string>
#include <vector>

namespace od::model {

/**
 * @brief Вид функции изменения мнений `g(s)`.
 *
 * Функция отвечает на вопрос: насколько вершину тянет к мнению, если оно есть у доли `s`
 * её соседей (`s` от 0 до 1). Значение функции считается для каждого мнения соседей,
 * и каждое мнение получает свою часть от общей суммы: `P(k) = g(sₖ) / Σₘ g(sₘ)`.
 *
 * Главное — как функция относится к популярным и редким мнениям.
 * При правиле выбора «пропорционально»:
 * - `g = s` — вершина как будто копирует мнение случайного соседа (модель избирателя).
 *   Шанс мнения ровно равен его доле среди соседей. Даже одна упрямая вершина со временем
 *   перетягивает на себя весь связный граф;
 * - `g = s²` или `g = e^(b·s)` — «стадный эффект»: популярному мнению достаётся больше
 *   его доли, редкому — меньше. Например, при `s²` мнение, которое есть у 30% соседей,
 *   получает не 30%, а около 16%. Поэтому меньшинство побеждает, только если его
 *   достаточно много;
 * - например `g = −s² + 2s` — наоборот, редкому мнению достаётся больше его доли,
 *   и разные мнения долго живут вместе.
 *
 * При правиле «максимум» у всех растущих функций вершина тянется к одному и тому же
 * мнению — самому частому у соседей, а функция влияет в основном на то, как быстро
 * вершина уступит (см. `ChoiceRule`).
 *
 * Если все коэффициенты полинома или множитель `a` экспоненты умножить на одно и то же число,
 * ничего не изменится: `2s²` и `s²` работают одинаково. Сделать одно мнение «сильнее»
 * остальных может только функция Морана.
 */
enum class OpinionFunctionKind {
    /**
     * Пороговая. Пока мнение есть не больше чем у доли `k1` соседей, оно не действует вовсе
     * (`f = 0`). Дальше влияние растёт по прямой, и при доле больше `k2` мнение принимается
     * наверняка (`f = 1`): `f(s) = (s − k1)/(k2 − k1)` между порогами.
     * Похоже на человека, который не обращает внимания на единичные мнения, но сдаётся,
     * когда так думает заметная часть окружения. При `k1 = 0`, `k2 = 1` получается `f = s`,
     * то есть модель избирателя.
     */
    Threshold,
    /**
     * Процесс Морана (пришёл из генетики, где так описывают распространение нового признака).
     * Одно мнение — «мутант» — получает преимущество: у него `g = (1 + δ)·s`, у остальных `g = s`.
     * - `δ > 0` — мутант заразительнее остальных: при `δ = 0.5` его перенимают в полтора раза охотнее;
     * - `δ = 0` — все мнения равны, это модель избирателя;
     * - `δ < 0` — мутант хуже остальных, при `δ = −1` его не перенимают никогда.
     *
     * Для двух мнений и правила «пропорционально» `P(мутант) = (1 + δ)·s / (1 + δ·s)`.
     */
    Moran,
    /**
     * Полином `g(s) = a·sⁿ + b·sⁿ⁻¹ + … + свободный член`, коэффициенты пишутся от старшей
     * степени. Прямая `a + b·s` — полином первой степени с коэффициентами `b, a`.
     * Примеры: `1, 0` — это `s` (модель избирателя); `1, 0, 0` — это `s²` (стадный эффект);
     * свободный член больше нуля — «шум»: вершина иногда переходит даже в очень редкое
     * мнение соседей.
     */
    Polynomial,
    /**
     * Экспонента `g(s) = a·e^(b·s)`. `b` — насколько сильно вершина идёт за большинством:
     * при `b = 0` все мнения соседей равновероятны, у скольких бы соседей они ни были,
     * а при большом `b` вершина почти всегда выбирает самое частое. `a` ни на что не влияет:
     * при подсчёте вероятностей он сокращается.
     */
    Exponential,
    /// Служебная: забирает всю вероятность, которая не досталась другим мнениям. Пользователь её не выбирает.
    Rest
};

/**
 * @brief Как вершина выбирает новое мнение по вероятностям `P(k)`.
 *
 * Вероятности есть только у мнений, которые есть хотя бы у одного соседа.
 *
 * **Пропорционально** — как рулетка: у каждого мнения свой сектор размером `P(k)`,
 * рулетку крутят один раз, и вершина берёт выпавшее мнение (может выпасть и её собственное).
 * Выиграть может любое мнение соседей, даже редкое.
 *
 * **Максимум** — в два шага:
 * 1. выбираем кандидата — мнение с самой большой `P(k)`. Если таких несколько, берём то,
 *    что выше в списке популярности, а если никого из них там нет — случайное из них;
 * 2. бросаем монетку: с вероятностью `P(кандидата)` вершина переходит к кандидату,
 *    иначе остаётся при своём мнении.
 *
 * Если функция растущая, кандидат — всегда самое частое мнение среди соседей. Поэтому
 * «максимум» значит «иди за большинством, но не сразу»: функция решает только, как быстро
 * вершина сдастся. Редкое мнение при этом правиле распространяется, только если у какой-то
 * вершины оно оказалось в большинстве среди её соседей.
 *
 * Новые прогоны по умолчанию используют «максимум». Старые файлы, где правило не записано,
 * читаются как «пропорционально» — так они повторяются без изменений.
 */
enum class ChoiceRule {
    Proportional, ///< Мнение `k` выбирается случайно с вероятностью `P(k)`.
    Max           ///< Кандидат — мнение с наибольшей `P(k)`, переход в него с вероятностью `P(кандидата)`.
};

/// @brief Число мнений по умолчанию: бинарная модель с мнениями 0 и 1.
constexpr int DEFAULT_NUM_OPINIONS = 2;

/// @brief Наибольшее допустимое число мнений.
constexpr int MAX_OPINIONS = 10000;

/// @brief Мнение-мутант процесса Морана, если оно не задано вторым параметром.
constexpr int DEFAULT_MORAN_MUTANT = 1;

/**
 * @brief Функция изменения мнений.
 *
 * Аргумент функции — доля `s` соседей вершины, у которых данное мнение (с весами рёбер или без).
 * Значение — «сила притяжения» мнения: чем оно больше, тем вероятнее вершина его примет.
 * Отрицательные значения и `NaN` считаются нулём.
 *
 * Сейчас в модели одна функция на все мнения, её превращает в правило `makeRule`.
 * У функции Морана необязательный второй параметр — номер мнения-мутанта.
 */
struct OpinionFunction {
    OpinionFunctionKind kind = OpinionFunctionKind::Threshold;
    std::vector<double> params = {0.0, 1.0};
};

/**
 * @brief Правило смены мнений: своя функция для каждого мнения.
 *
 * Сделано с запасом на будущее, когда у каждого мнения может быть своя функция.
 * Сейчас правило строится из одной функции через `makeRule`.
 *
 * Вершина считает `gₖ(sₖ)` для мнений соседей, и каждое мнение получает свою часть суммы:
 * `P(k) = gₖ(sₖ) / Σₘ gₘ(sₘ)`. Если у одного мнения функция `Rest` (классическая пороговая
 * модель), значения остальных функций сразу считаются вероятностями, а мнение с `Rest`
 * получает всё, что осталось до 1, даже если его нет у соседей. Если сумма остальных больше 1,
 * они делятся на эту сумму, и мнению с `Rest` не остаётся ничего.
 */
struct OpinionRule {
    std::vector<OpinionFunction> functions; ///< Функция мнения `k` — `functions[k]`, размер равен числу мнений.
    int restOpinion = -1;                   ///< Мнение с функцией `Rest` или −1, если такого нет.
};

/// @brief Доля соседей вершины с одним мнением.
struct OpinionShare {
    int opinion;  ///< Номер мнения.
    double share; ///< Доля соседей с этим мнением, от 0 до 1.
};

/// @brief Вероятность перейти в мнение.
struct OpinionChance {
    int opinion;        ///< Номер мнения.
    double probability; ///< Вероятность перехода.
};

/// @brief Значение функции влияния при доле соседей `share`, не меньше нуля.
/// Функция должна быть корректной (`validateOpinionFunction` вернула пустую строку).
double evaluateInfluence(const OpinionFunction& function, double share);

/**
 * @brief Вероятности перейти в мнения при заданных долях соседей.
 *
 * Считаются только мнения из `shares`, то есть те, что есть у соседей, и мнение с `Rest`,
 * если оно есть в правиле. Остальные мнения получают 0, поэтому время работы не зависит
 * от того, сколько всего мнений в модели.
 *
 * Обычно `P(k) = gₖ(sₖ) / Σₘ gₘ(sₘ)`. С `Rest` — по схеме из описания `OpinionRule`.
 *
 * @param rule Правило смены мнений.
 * @param shares Доли мнений соседей по возрастанию номера мнения, номера меньше `rule.functions.size()`.
 * @return Вероятности в порядке розыгрыша: мнения из `shares` по возрастанию, мнение с `Rest` последним.
 *         Сумма равна 1 или все вероятности нулевые — тогда вершина сохраняет мнение.
 */
std::vector<OpinionChance> adoptionProbabilities(const OpinionRule& rule, const std::vector<OpinionShare>& shares);

/**
 * @brief Строит правило смены мнений из одной функции модели.
 *
 * - `threshold(k1, k2)` при правиле `Proportional` — классическая пороговая модель: мнение 0
 *   получает остаток (`Rest`), остальные мнения `k` принимаются с вероятностью `f(sₖ)`.
 *   При двух мнениях это «мнение 1 с вероятностью `f(s₁)`, иначе 0». При правиле `Max`
 *   функция `f` одна у всех мнений, как у остальных функций;
 * - `moran(δ[, мутант])`: у мнения-мутанта (по умолчанию 1) `(1 + δ)·s`, у остальных `s`;
 * - `polynomial`, `exponential`: одна и та же функция у всех мнений.
 *
 * @param function Функция модели, должна пройти `validateOpinionSettings` для `numOpinions`.
 * @param numOpinions Число мнений, от 2 до `MAX_OPINIONS`.
 * @param choice Правило выбора нового мнения.
 */
OpinionRule makeRule(const OpinionFunction& function, int numOpinions, ChoiceRule choice);

/// @brief Пороговая функция с порогами `k1`, `k2`.
OpinionFunction thresholdFunction(double k1, double k2);

/// @brief Функция по умолчанию: пороговая с k1 = 0, k2 = 1.
OpinionFunction defaultOpinionFunction();

/// @brief Мнение-мутант функции Морана: второй параметр или `DEFAULT_MORAN_MUTANT`.
int moranMutant(const OpinionFunction& function);

/// @brief Функции, которые можно выбрать для модели (без служебной `Rest`).
std::vector<OpinionFunctionKind> allOpinionKinds();
std::string opinionKindToString(OpinionFunctionKind kind);
std::optional<OpinionFunctionKind> opinionKindFromString(const std::string& name);
std::string opinionKindDisplayName(OpinionFunctionKind kind);
std::string opinionParamsDescription(OpinionFunctionKind kind);

/// @brief Имя правила выбора в файлах и флагах: `proportional` или `max`.
std::string choiceRuleToString(ChoiceRule rule);
std::optional<ChoiceRule> choiceRuleFromString(const std::string& name);

/// @brief Название правила выбора для вывода: «пропорционально» или «максимум».
std::string choiceRuleDisplayName(ChoiceRule rule);

/// @brief Текст ошибки, если функцию нельзя использовать в модели, иначе пустая строка.
std::string validateOpinionFunction(const OpinionFunction& function);

/// @brief Текст ошибки, если в списке популярности есть мнение вне `0..numOpinions − 1` или повтор.
std::string validatePopularity(const std::vector<int>& popularity, int numOpinions);

/**
 * @brief Проверяет функцию и список популярности для модели с `numOpinions` мнениями.
 *
 * Кроме `validateOpinionFunction` проверяет, что мутант Морана меньше `numOpinions`,
 * а в списке популярности мнения от 0 до `numOpinions − 1` без повторов.
 *
 * @return Текст ошибки или пустая строка.
 */
std::string validateOpinionSettings(const OpinionFunction& function, const std::vector<int>& popularity,
                                    int numOpinions);

/// @brief Текст ошибки, если правило некорректно, иначе пустая строка.
std::string validateOpinionRule(const OpinionRule& rule);

/// @brief Краткая запись функции, например `moran(0.5)`.
std::string describeOpinionFunction(const OpinionFunction& function);

/// @brief Список мнений через запятую, например `5, 3, 2`.
std::string describeOpinionList(const std::vector<int>& opinions);

} // namespace od::model
