#pragma once

#include "od/config/RuntimeParams.hpp"

#include <vector>

namespace od::model {

/**
 * @brief Проводит один прогон симуляции и сохраняет результаты в новую папку.
 *
 * ### По шагам
 *
 * 1. Проверяем параметры. Если seed не задан, выбираем случайный.
 * 2. Задаём начальные мнения: берём готовые из файла графа или строим по настройкам.
 * 3. Создаём папку прогона и сохраняем `graph_initial.txt` — граф, начальные мнения и все
 *    параметры. По этому файлу прогон можно повторить точь-в-точь.
 * 4. Делаем `T_MAX` шагов. На каждом шаге:
 *    1. если включена динамика рёбер — часть связей появляется, часть пропадает;
 *    2. все обычные вершины одновременно обновляют мнения, уже на изменённом графе;
 *    3. в лог записывается, кто сменил мнение и сколько вершин у каждого мнения.
 * 5. Сохраняем `graph_final.txt` (граф и мнения в конце) и `simulation_log.txt`.
 *
 * Шаги в файлах и в консоли считаются с 1.
 *
 * ### Повторяемость
 *
 * Весь прогон определяется одним seed. Для графа, для случайных начальных мнений и для самой
 * симуляции случайные числа берутся из трёх отдельных источников, которые выводятся из этого
 * seed. Поэтому, например, если включить случайные начальные мнения, граф останется тем же.
 * Одинаковые настройки и seed дают одинаковые файлы до последнего байта.
 *
 * ### Папка прогона
 *
 * Папка называется `<runsDir>/run_<seed>` (по умолчанию `runs/run_<seed>`). Если она уже есть,
 * берётся `run_<seed>_2`, `run_<seed>_3` и так далее — старые прогоны не перезаписываются.
 * Ход прогона печатается в консоль, в тихом режиме — только папка прогона и итог.
 *
 * @param graph Начальный граф, изменяется по ходу симуляции.
 * @param params Параметры прогона. Если seed не задан, он выбирается случайно.
 * @param initialOpinions Готовые начальные мнения или пусто — тогда они строятся
 *        по `params.initialOpinions`.
 * @param output Папка для прогонов и подробность вывода в консоль.
 * @throws std::invalid_argument Если параметры не проходят `od::config::validateParams`
 *         или готовые мнения не подходят к графу и числу мнений.
 */
void runSimulation(od::graph::Graph graph, od::config::RuntimeParams params, std::vector<int> initialOpinions,
                   const od::config::OutputOptions& output);

} // namespace od::model
