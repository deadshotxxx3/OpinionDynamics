#pragma once

#include "od/graph/Graph.hpp"

#include <random>
#include <vector>

namespace od::model {

using od::graph::Graph;

/// @brief Одно изменение ребра за шаг симуляции, записывается в лог.
struct EdgeEvent {
    int step;      ///< Номер шага (с 1), на котором произошло изменение.
    bool added;    ///< `true` — ребро появилось, `false` — исчезло.
    int u;         ///< Первый конец ребра, `u < v`.
    int v;         ///< Второй конец ребра.
    double weight; ///< Вес нового ребра или вес исчезнувшего.
};

/**
 * @brief Один шаг изменения связей: новые рёбра появляются, старые пропадают.
 *
 * Моделирует то, что люди со временем заводят новые знакомства и теряют старые.
 * На каждом шаге для каждой пары вершин:
 * - если ребра нет, оно появляется с вероятностью `p_add` и получает случайный вес от 0 до 1;
 * - если ребро есть, оно пропадает с вероятностью `p_remove`.
 *
 * За один шаг пара меняется не больше одного раза: только что появившееся ребро в этом же
 * шаге не пропадёт. Пропасть может любое ребро, в том числе единственное ребро
 * прикреплённой упрямой вершины — тогда она остаётся без соседей.
 *
 * Если обе вероятности не меняются со временем, доля соединённых пар в итоге
 * устанавливается около `p_add / (p_add + p_remove)`, каким бы граф ни был вначале.
 * Например, при `p_add = 0.01` и `p_remove = 0.04` со временем будет соединена
 * примерно пятая часть всех пар.
 *
 * Перебираются все пары вершин, поэтому на больших графах это самая медленная часть
 * симуляции. Если обе вероятности нулевые, шаг ничего не делает и не тратит случайные числа.
 *
 * @param graph Граф, изменяется на месте.
 * @param addProbability Вероятность появления ребра на этом шаге, от 0 до 1.
 * @param removeProbability Вероятность исчезновения ребра на этом шаге, от 0 до 1.
 * @param rng Генератор случайных чисел симуляции.
 * @param step Номер шага для записи в `events`.
 * @param events Сюда дописываются все изменения рёбер за шаг.
 */
void evolveEdges(
    Graph& graph,
    double addProbability,
    double removeProbability,
    std::mt19937& rng,
    int step,
    std::vector<EdgeEvent>& events);

} // namespace od::model
